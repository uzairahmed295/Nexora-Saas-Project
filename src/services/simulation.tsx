import { useEffect } from "react";
import { atomic } from "../db/database";
import { createOrderInDraft } from "./orders";
import { can } from "./permissions";
import { useWorkspace } from "../store/workspace";
import { useToast } from "../components/Feedback";
import { now } from "../utils/format";
export async function simulateEvent() {
  await atomic((d) => {
    const s = d.settings[0];
    if (!s.simulation || !s.demoMode) return;
    const role = d.users.find((u) => u.id === s.currentUserId)?.role;
    if (!can(role, "commerce")) return;
    const products = d.products.filter(
      (p) => p.status === "Active" && p.stock > 2,
    );
    if (!products.length || !d.customers.length) return;
    const seq = s.simulationSequence++;
    const p = products[seq % products.length];
    const c = d.customers[(seq * 3) % d.customers.length];
    createOrderInDraft(d, {
      id: `simulation-${s.seedDate}-${seq}`,
      customerId: c.id,
      items: [{ productId: p.id, quantity: 1 + (seq % 2) }],
      discount: 0,
      taxRate: 8,
      paymentStatus: "Paid",
      notes: "Generated by optional live demo simulation.",
      source: "Simulation",
    });
    s.updatedAt = now();
  });
}
export function SimulationBridge() {
  const { data } = useWorkspace();
  const toast = useToast();
  const active = data.settings[0].simulation && data.settings[0].demoMode;
  useEffect(() => {
    if (!active) return;
    const id = setInterval(() => {
      if (document.visibilityState !== "visible") return;
      void simulateEvent().catch(() =>
        toast(
          "Simulation paused this event. Check available products and stock.",
          "warning",
        ),
      );
    }, 45000);
    return () => clearInterval(id);
  }, [active, toast]);
  return null;
}
